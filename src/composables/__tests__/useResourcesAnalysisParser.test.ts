// ── Parser tests ──────────────────────────────────────────────────────────────

describe('parseResourcesAnalysis — happy path', () => {
  it('round-trips a fully-formed analysis JSON', () => {
    const { ok, data, errors, warnings } = parseResourcesAnalysis(JSON.stringify(goodAnalysis))
    expect(ok).toBe(true)
    expect(errors).toEqual([])
    expect(warnings).toEqual([])
    expect(data?.schemaVersion).toBe('1')
    expect(data?.partA?.['calendar-time']).toHaveLength(1)
    expect(data?.partA?.['calendar-time']?.[0].title).toContain('Delivery deadline tight')
    expect(data?.partA?.['calendar-time']?.[0].proposedREntry?.id).toBe('R.SpecialistAvailability.NavalArchitect')
    expect(data?.partA?.['calendar-time']?.[0].tradeoff?.approvedBy).toBe('Sponsor')
    expect(data?.partB?.['resource-constraint-specs']?.proposedREntries).toHaveLength(1)
    expect(data?.partB?.['binary-constraints-for-resources']?.proposedCEntries).toHaveLength(1)
    expect(data?.partB?.['resource-management-strategies']?.proposedSEntries).toHaveLength(1)
    expect(data?.partB?.['scale-and-meter-improvement']?.proposedFieldEdits).toHaveLength(1)
  })

  it('passes through unknown extra fields without complaint (forward-compat)', () => {
    const withExtras = { ...goodAnalysis, futureField: 'whatever' }
    const { ok } = parseResourcesAnalysis(JSON.stringify(withExtras))
    expect(ok).toBe(true)
  })

  it('accepts empty partA / partB but emits warning', () => {
    const { ok, warnings } = parseResourcesAnalysis(JSON.stringify({}))
    expect(ok).toBe(true)
    expect(warnings.some((w) => w.includes('No `partA` or `partB`'))).toBe(true)
  })
})

describe('parseResourcesAnalysis — error paths', () => {
  it('rejects empty input', () => {
    const { ok, errors } = parseResourcesAnalysis('')
    expect(ok).toBe(false)
    expect(errors[0]).toContain('Input is empty')
  })

  it('rejects malformed JSON with the parse-error message', () => {
    const { ok, errors } = parseResourcesAnalysis('{not json')
    expect(ok).toBe(false)
    expect(errors[0]).toContain('Not valid JSON')
  })

  it('rejects non-object top-level', () => {
    expect(parseResourcesAnalysis('[]').ok).toBe(false)
    expect(parseResourcesAnalysis('"string"').ok).toBe(false)
    expect(parseResourcesAnalysis('42').ok).toBe(false)
  })

  it('rejects partA that is not an object', () => {
    const { ok, errors } = parseResourcesAnalysis(JSON.stringify({ partA: 'string' }))
    expect(ok).toBe(false)
    expect(errors.some((e) => e.includes('partA'))).toBe(true)
  })

  it('rejects a non-array dimension under partA', () => {
    const { ok, errors } = parseResourcesAnalysis(JSON.stringify({ partA: { 'calendar-time': 'oops' } }))
    expect(ok).toBe(false)
    expect(errors.some((e) => e.includes('partA.calendar-time'))).toBe(true)
  })

  it('requires title on every finding', () => {
    const { ok, errors } = parseResourcesAnalysis(JSON.stringify({
      partA: { 'calendar-time': [{ description: 'missing title' }] }
    }))
    expect(ok).toBe(false)
    expect(errors.some((e) => e.includes('title'))).toBe(true)
  })

  it('warns when severity is invalid but defaults to info', () => {
    const { ok, data, warnings } = parseResourcesAnalysis(JSON.stringify({
      partA: { 'calendar-time': [{ title: 'X', description: 'y', severity: 'meh' }] }
    }))
    expect(ok).toBe(true)
    expect(data?.partA?.['calendar-time']?.[0].severity).toBe('info')
    expect(warnings.some((w) => w.includes('severity'))).toBe(true)
  })

  it('warns when source=cited-from-gilb but gilbCite missing (provenance unverifiable)', () => {
    const { warnings } = parseResourcesAnalysis(JSON.stringify({
      partA: { 'calendar-time': [{ title: 'X', description: 'y', source: 'cited-from-gilb' }] }
    }))
    expect(warnings.some((w) => w.includes('cited-from-gilb but no gilbCite'))).toBe(true)
  })
})

