// ── Apply-handler tests ───────────────────────────────────────────────────────

describe('applyApprovedToSpec — write-back behaviour', () => {
  const approvals: ApprovalSet = {
    rEntries:   [{ id: 'R.A', scale: 's', tolerable: 't', goal: 'g' }],
    sEntries:   [{ id: 'S.A', description: 'd', impact: 'i' }],
    cEntries:   [{ id: 'C.A', description: 'd' }],
    fieldEdits: [],
  }

  it('adds new R/S/C entries to an empty spec', () => {
    const next = applyApprovedToSpec(emptySpec(), approvals)
    expect(next.resources).toHaveLength(1)
    expect(next.solutions).toHaveLength(1)
    expect(next.constraints).toHaveLength(1)
    expect(next.resources?.[0].id).toBe('R.A')
  })

  it('is idempotent — applying twice yields the same result (upsert by id)', () => {
    const first  = applyApprovedToSpec(emptySpec(), approvals)
    const second = applyApprovedToSpec(first, approvals)
    expect(second.resources).toHaveLength(1)
    expect(second.solutions).toHaveLength(1)
    expect(second.constraints).toHaveLength(1)
  })

  it('does NOT mutate the input spec', () => {
    const spec = emptySpec()
    applyApprovedToSpec(spec, approvals)
    expect(spec.resources).toEqual([])
    expect(spec.solutions).toEqual([])
    expect(spec.constraints).toEqual([])
  })

  it('preserves existing entries with different ids', () => {
    const spec: SpecBlock = {
      ...emptySpec(),
      resources:   [{ id: 'R.Existing',   type: 'Resource',   level: 'Product', description: 'x', scale: '', meter: '', status: '', tolerable: '', goal: '' }],
      solutions:   [{ id: 'S.Existing',   type: 'Solution',   level: 'Product', description: 'x', impact: '', function: '' }],
      constraints: [{ id: 'C.Existing',   type: 'Constraint', level: 'Product', description: 'x', scope: '', rationale: '' }],
    }
    const next = applyApprovedToSpec(spec, approvals)
    expect(next.resources?.map((r) => r.id).sort()).toEqual(['R.A', 'R.Existing'])
    expect(next.solutions?.map((s) => s.id).sort()).toEqual(['S.A', 'S.Existing'])
    expect(next.constraints?.map((c) => c.id).sort()).toEqual(['C.A', 'C.Existing'])
  })

  it('replaces existing entries with the same id (upsert)', () => {
    const spec: SpecBlock = {
      ...emptySpec(),
      resources: [{ id: 'R.A', type: 'Resource', level: 'Product', description: 'old', scale: 'old-scale', meter: '', status: '', tolerable: '', goal: '' }],
    }
    const next = applyApprovedToSpec(spec, approvals)
    expect(next.resources).toHaveLength(1)
    expect(next.resources?.[0].scale).toBe('s')  // from approval, not 'old-scale'
  })

  it('applies field edits to existing entries in place', () => {
    const spec: SpecBlock = {
      ...emptySpec(),
      resources: [{ id: 'R.A', type: 'Resource', level: 'Product', description: 'd', scale: 'OLD_SCALE', meter: '', status: '', tolerable: '', goal: '' }],
    }
    const a: ApprovalSet = {
      rEntries: [], sEntries: [], cEntries: [],
      fieldEdits: [{ entryId: 'R.A', field: 'scale', proposedValue: 'NEW_SCALE_QUALIFIED' }],
    }
    const next = applyApprovedToSpec(spec, a)
    expect(next.resources?.[0].scale).toBe('NEW_SCALE_QUALIFIED')
  })

  it('does NOT add resources when none approved (preserves untouched spec.resources)', () => {
    const spec: SpecBlock = {
      ...emptySpec(),
      resources: [{ id: 'R.Existing', type: 'Resource', level: 'Product', description: 'x', scale: '', meter: '', status: '', tolerable: '', goal: '' }],
    }
    const a: ApprovalSet = { rEntries: [], sEntries: [], cEntries: [], fieldEdits: [] }
    const next = applyApprovedToSpec(spec, a)
    expect(next.resources).toHaveLength(1)
    expect(next.resources?.[0].id).toBe('R.Existing')
  })
})
