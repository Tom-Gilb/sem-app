 *      outside, or ✕ close.  Clicking a star in fullscreen also auto-closes
 *      so the parent picker lands on the new concept.
 *
 *   B. Category labels at constellation centres — small white text at the
 *      centroid of each category's star cluster.  Labels render at 45 %
 *      opacity normally → 100 % when any star in that constellation is
 *      hovered OR the filter has any matches in that category.  Categories
 *      with < 3 concepts get hover-only labels so the universe doesn't
 *      clutter.
 *
 *   C. Embedded filter input — ⌕ field in the header.  Type to dim non-
 *      matching stars to 12 % opacity; matches stay full brightness +
 *      grow 1.5×.  Match count next to the field.  Enter on a single
 *      remaining match navigates to it.  Separate scope from the picker's
 *      main search box — filter operates within the universe only.
 *
 * Loads /planguage-ontology-tree.json (already in /public/, generated by
 * 10.Standard/2.Glossary/PlanguageGlossary/_build-ontology-tree.py).
