import { ref, computed, onMounted, onBeforeUnmount, nextTick } from 'vue'
import CloseDot from './CloseDot.vue'  // r41 v18 (Tom Gilb 2026-06-14: "the close button is NOT our sem standard")

interface OntologyConcept {
  id:             string
  kind:           'concept'
  name:           string
  conceptNumber?: string
  type?:          string
  keyedIcon?:     string
  twinUrl?:       string
  definition?:    string
}
interface OntologyCategory {
  id:       string
  kind:     'class'
  name:     string
  slug?:    string
  children: Array<OntologyConcept | OntologyCategory>
}
interface OntologyTree {
  totalConcepts:   number
  totalCategories: number
  tree:            OntologyCategory
}

interface StarLayout {
  concept:  OntologyConcept
  category: string
  cx:       number
  cy:       number
  r:        number
  color:    string
}

interface ConstellationLabel {
  name:     string
  color:    string
  cx:       number  // centroid x
  cy:       number  // centroid y
  size:     number  // concept count
}

const emit = defineEmits<{
  (e: 'select-concept', name: string): void
}>()

withDefaults(defineProps<{
  size?: number
}>(), {
  size: 720,
})

const _tree = ref<OntologyTree | null>(null)
const _error = ref<string | null>(null)
const _hoveredStar = ref<StarLayout | null>(null)
const _hoveredCategory = ref<string | null>(null)
const _hoverX = ref(0)
const _hoverY = ref(0)

// A — fullscreen lightbox state
const _fullscreen = ref(false)
function openFullscreen(): void {
  _fullscreen.value = true
  // Lock background scroll
  if (typeof document !== 'undefined') {
    document.body.style.overflow = 'hidden'
  }
}
function closeFullscreen(): void {
  _fullscreen.value = false
  if (typeof document !== 'undefined') {
    document.body.style.overflow = ''
  }
}
function _onKey(e: KeyboardEvent): void {
  if (e.key === 'Escape' && _fullscreen.value) {
    e.stopPropagation()
    closeFullscreen()
  }
  // r41 v25 (Tom Gilb 2026-06-14 verbatim: "black window stuck in place") —
  // Escape also clears any stranded HoverHint.  Composes with the scroll +
  // mouseleave clearers below.
  if (e.key === 'Escape' && _hoveredStar.value) {
    _hoveredStar.value = null
    _hoveredCategory.value = null
  }
}

// r41 v25 — Stranded-HoverHint fix.
//
// Bug: the floating HoverHint uses `position: fixed`, so when the picker body
// scrolls past the Universe SVG OR the cursor exits the SVG between stars
// (without crossing any star's edge), no `mouseleave` fires on the <g> and
// `_hoveredStar` stays set.  The black box hangs in place over whatever
// content scrolled into its viewport coords — e.g. the Task ontology diagram.
//
// Three defensive clearers:
//   (1) @mouseleave on the SVG + the wrap div (template) — any cursor exit
//   (2) capture-phase window 'scroll' + 'wheel' listeners (here) — any scroll
//       inside any ancestor clears the HoverHint
//   (3) Escape key (above) — explicit dismissal affordance
function _clearStrandedHint(): void {
  if (_hoveredStar.value) {
    _hoveredStar.value = null
    _hoveredCategory.value = null
  }
}

onMounted(() => {
  document.addEventListener('keydown', _onKey, true)
  // Capture phase + passive so we hear scroll on every ancestor (the picker
  // body, the modal, the window) without interfering with normal scrolling.
  window.addEventListener('scroll', _clearStrandedHint, { capture: true, passive: true })
  window.addEventListener('wheel',  _clearStrandedHint, { capture: true, passive: true })
})
onBeforeUnmount(() => {
  document.removeEventListener('keydown', _onKey, true)
  window.removeEventListener('scroll', _clearStrandedHint, { capture: true } as EventListenerOptions)
  window.removeEventListener('wheel',  _clearStrandedHint, { capture: true } as EventListenerOptions)
  // Defensive — release background scroll lock if we get unmounted mid-fullscreen
  if (typeof document !== 'undefined') document.body.style.overflow = ''
})

// C — embedded filter
const _filterText = ref('')
const _filterInputRef = ref<HTMLInputElement | null>(null)
const _filterInputFsRef = ref<HTMLInputElement | null>(null)

const PALETTE = [
  '#a78bfa', '#6ee7b7', '#fbbf24', '#fb923c', '#f87171',
  '#60a5fa', '#22d3ee', '#c084fc', '#fde68a', '#67e8f9',
]

onMounted(async () => {
  try {
    const res = await fetch(`/planguage-ontology-tree.json?v=${Date.now() % 100000}`)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    _tree.value = await res.json()
  } catch (e) {
    _error.value = `Could not load /planguage-ontology-tree.json: ${(e as Error).message}`
    console.warn('[PlanguageUniverse]', _error.value)
  }
})

const categories = computed<Array<{ name: string; concepts: OntologyConcept[] }>>(() => {
  const t = _tree.value
  if (!t) return []
  const out: Array<{ name: string; concepts: OntologyConcept[] }> = []
  for (const cat of t.tree.children) {
    if (cat.kind !== 'class') continue
    const concepts = cat.children.filter((x): x is OntologyConcept => x.kind === 'concept')
    if (concepts.length === 0) continue
    out.push({ name: cat.name, concepts })
  }
  out.sort((a, b) => b.concepts.length - a.concepts.length)
  return out
})

const stars = computed<StarLayout[]>(() => {
  const cats = categories.value
  if (cats.length === 0) return []
  const out: StarLayout[] = []
  const centreX = 360
  const centreY = 360
  const innerR = 90
  const outerR = 330
  const totalWeight = cats.reduce((s, c) => s + Math.sqrt(c.concepts.length), 0)
  let angleSoFar = -Math.PI / 2
  cats.forEach((cat, i) => {
    const slice = (Math.sqrt(cat.concepts.length) / totalWeight) * Math.PI * 2
    const colour = PALETTE[i % PALETTE.length]
    cat.concepts.forEach((concept, j) => {
      const tRadial = cat.concepts.length === 1 ? 0.5 : j / (cat.concepts.length - 1)
      const r = innerR + tRadial * (outerR - innerR)
      const tAngular = cat.concepts.length === 1 ? 0.5 : (j % 7) / 7
      const angle = angleSoFar + slice * (0.15 + tAngular * 0.7)
      const n = parseInt(concept.conceptNumber ?? '500', 10) || 500
      const baseR = 2.2 + Math.max(0, (500 - n) / 350) * 3
      out.push({
        concept,
        category: cat.name,
        cx: centreX + Math.cos(angle) * r,
        cy: centreY + Math.sin(angle) * r,
        r: baseR,
        color: colour,
      })
    })
    angleSoFar += slice
  })
  return out
})

// B — constellation centroid labels
const constellationLabels = computed<ConstellationLabel[]>(() => {
  const map = new Map<string, { cxSum: number; cySum: number; count: number; color: string }>()
  for (const s of stars.value) {
    const e = map.get(s.category) ?? { cxSum: 0, cySum: 0, count: 0, color: s.color }
    e.cxSum += s.cx
    e.cySum += s.cy
    e.count++
    e.color = s.color
    map.set(s.category, e)
  }
  return Array.from(map.entries()).map(([name, e]) => ({
    name,
    color:  e.color,
    cx:     e.cxSum / e.count,
    cy:     e.cySum / e.count,
    size:   e.count,
  }))
})

// C — filter-matched concept ids
const filteredStarIds = computed<Set<string>>(() => {
  const q = _filterText.value.trim().toLowerCase()
  if (!q) return new Set()  // empty = no filter applied (all stars rendered at full brightness)
  const out = new Set<string>()
  for (const s of stars.value) {
    if (
      s.concept.name.toLowerCase().includes(q)
      || s.category.toLowerCase().includes(q)
      || (s.concept.conceptNumber ?? '').includes(q)
      || (s.concept.definition ?? '').toLowerCase().includes(q)
    ) {
      out.add(s.concept.id)
    }
  }
  return out
})

const filterActive = computed(() => _filterText.value.trim().length > 0)
const filterMatchCount = computed(() => filteredStarIds.value.size)

const filteredCategories = computed<Set<string>>(() => {
  if (!filterActive.value) return new Set()
  const out = new Set<string>()
  for (const s of stars.value) {
    if (filteredStarIds.value.has(s.concept.id)) out.add(s.category)
  }
  return out
})

function isStarVisible(s: StarLayout): { opacity: number; rMul: number } {
  if (!filterActive.value) return { opacity: 1, rMul: 1 }
  if (filteredStarIds.value.has(s.concept.id)) return { opacity: 1, rMul: 1.5 }
  return { opacity: 0.12, rMul: 1 }
}

function isCategoryLit(name: string): boolean {
  // B — label brightening logic:
  //   - filter active AND this category has matches → bright
  //   - any star in this category hovered → bright
  //   - otherwise dim (or hidden for small constellations)
  if (filterActive.value && filteredCategories.value.has(name)) return true
  if (_hoveredCategory.value === name) return true
  return false
}

function categoryLabelOpacity(c: ConstellationLabel): number {
  if (isCategoryLit(c.name)) return 1
  // Small constellations only show on hover/filter
  if (c.size < 3) return 0
  return 0.42
}

function onStarHover(s: StarLayout, ev: MouseEvent): void {
  _hoveredStar.value = s
  _hoveredCategory.value = s.category
  _hoverX.value = ev.clientX
  _hoverY.value = ev.clientY
}
function onStarMouseMove(ev: MouseEvent): void {
  _hoverX.value = ev.clientX
  _hoverY.value = ev.clientY
}
function onStarLeave(): void {
  _hoveredStar.value = null
  _hoveredCategory.value = null
}
function onStarClick(s: StarLayout): void {
  emit('select-concept', s.concept.name)
  if (_fullscreen.value) closeFullscreen()
}

function onFilterEnter(): void {
  // If exactly one match, navigate to it
  if (filterMatchCount.value === 1) {
    const id = Array.from(filteredStarIds.value)[0]
    const s = stars.value.find(x => x.concept.id === id)
    if (s) onStarClick(s)
  }
}

function clearFilter(): void {
  _filterText.value = ''
  if (_fullscreen.value) {
    nextTick(() => _filterInputFsRef.value?.focus())
  } else {
    nextTick(() => _filterInputRef.value?.focus())
  }
}

function _shortDef(d: string | undefined): string {
  if (!d) return ''
  const oneLine = d.replace(/\s+/g, ' ').trim()
  return oneLine.length > 240 ? oneLine.slice(0, 237) + '…' : oneLine
}
